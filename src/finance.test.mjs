import assert from 'node:assert/strict';
import { emptyData, dailyReport, formatRupees, parseRupees, categorize, parseStatement, categoryTotals, fingerprint, previewImport, recurringMerchants, monthlyRecap } from './finance.ts';
const data = emptyData();
data.profile.incomePaise = 10_000_000;
data.profile.setAsidePaise = 5_050_000;
assert.equal(formatRupees(dailyReport(data, '2026-10-22').income), '₹3,333');
assert.equal(formatRupees(dailyReport(data, '2026-10-22').allowance), '₹1,650');
data.transactions.push({ id: '1', date: '2026-10-22', description: 'Blinkit', amountPaise: 60_000, category: 'Groceries', source: 'manual' });
assert.equal(dailyReport(data, '2026-10-22').remaining, 105_000);
assert.equal(categorize('UPI/RAHUL'), 'UPI');
assert.equal(parseRupees('₹250.50'), 25050);
assert.equal(categoryTotals(data.transactions)[0].category, 'Groceries');
assert.equal(parseStatement('Date,Description,Debit\n22/10/2026,"Blue Tokai, coffee",250\n22/10/2026,Salary,').length, 1);
assert.equal(parseStatement('Date,Description,Amount,Type\n22/10/2026,Coffee,250,Debit\n22/10/2026,Salary,100000,Credit').length, 1);
assert.throws(() => parseStatement('Date,Description,Amount\n31/02/2026,Coffee,250'));
assert.equal(fingerprint('abc'), fingerprint('abc'));
const bankRows = parseStatement('Transaction Date;Particulars;Withdrawal Amount;Deposit Amount\n22-Oct-2026;SWIGGY;500;\n22-Oct-2026;Salary;;100000');
assert.equal(bankRows.length, 1);
assert.equal(bankRows[0].category, 'Food');
const existing = [{ id: 'old', ...bankRows[0] }];
const overlap = previewImport('Date,Description,Debit\n22/10/2026,SWIGGY,500\n22/10/2026,Blinkit,600', existing);
assert.equal(overlap.duplicates, 1);
assert.equal(overlap.additions.length, 1);
assert.equal(previewImport('Date,Description,Debit\n22/10/2026,SWIGGY,500', existing, [{ merchant: 'swiggy', category: 'Shopping' }]).rows[0].category, 'Shopping');
const months = [{ id: 'a', date: '2026-09-22', description: 'Netflix', amountPaise: 49900, category: 'Subscriptions', source: 'csv' }, { id: 'b', date: '2026-10-22', description: 'Netflix', amountPaise: 49900, category: 'Subscriptions', source: 'csv' }];
assert.equal(recurringMerchants(months)[0].merchant, 'netflix');
assert.equal(monthlyRecap(months, '2026-10-22').previousSpent, 49900);
assert.equal(parseStatement('Account statement\nGenerated today\nTransaction Date,Particulars,Amount (INR),DR/CR\n22-Oct-2026,Coffee,250,DR\n22-Oct-2026,Salary,100000,CR').length, 1);
assert.equal(parseStatement('Date,Description,Amount\n22/10/2026,Coffee,-250 DR')[0].amountPaise, 25000);
console.log('19 finance checks passed');
